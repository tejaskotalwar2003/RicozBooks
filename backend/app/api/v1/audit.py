import io
import csv
from typing import List, Optional
from datetime import datetime, timezone
from fastapi import APIRouter, Depends, Query, Response
from sqlalchemy.orm import Session
from sqlalchemy import desc, or_

from app.database.session import get_db
from app.models.user import User
from app.models.audit import AuditLog
from app.schemas.audit import AuditLogResponse, PaginatedAuditLogResponse
from app.api.deps import get_current_user, require_roles

router = APIRouter()

def build_audit_query(
    db: Session,
    entity_id: Optional[int] = None,
    action: Optional[str] = None,
    record_type: Optional[str] = None,
    user_email: Optional[str] = None,
    start_date: Optional[datetime] = None,
    end_date: Optional[datetime] = None,
    search: Optional[str] = None,
):
    query = db.query(AuditLog)
    if entity_id:
        query = query.filter(AuditLog.entity_id == entity_id)
    if action:
        query = query.filter(AuditLog.action == action)
    if record_type:
        query = query.filter(AuditLog.record_type == record_type)
    if user_email:
        query = query.filter(AuditLog.user_email.ilike(f"%{user_email}%"))
    if start_date:
        query = query.filter(AuditLog.timestamp >= start_date)
    if end_date:
        query = query.filter(AuditLog.timestamp <= end_date)
    if search:
        s = f"%{search}%"
        query = query.filter(
            or_(
                AuditLog.action.ilike(s),
                AuditLog.record_type.ilike(s),
                AuditLog.record_id.ilike(s),
                AuditLog.details.ilike(s),
                AuditLog.user_email.ilike(s)
            )
        )
    return query

@router.get("/audit-logs", response_model=PaginatedAuditLogResponse)
def get_audit_logs(
    entity_id: Optional[int] = Query(None),
    action: Optional[str] = Query(None),
    record_type: Optional[str] = Query(None),
    user_email: Optional[str] = Query(None),
    start_date: Optional[datetime] = Query(None),
    end_date: Optional[datetime] = Query(None),
    search: Optional[str] = Query(None),
    skip: int = Query(0, ge=0),
    limit: int = Query(50, ge=1, le=200),
    current_user: User = Depends(require_roles(["ADMIN", "REVIEWER", "ACCOUNTANT"])),
    db: Session = Depends(get_db)
):
    query = build_audit_query(
        db=db,
        entity_id=entity_id,
        action=action,
        record_type=record_type,
        user_email=user_email,
        start_date=start_date,
        end_date=end_date,
        search=search,
    )
    total = query.count()
    items = query.order_by(desc(AuditLog.timestamp)).offset(skip).limit(limit).all()
    return PaginatedAuditLogResponse(
        items=items,
        total=total,
        skip=skip,
        limit=limit
    )

@router.get("/audit-logs/export")
def export_audit_logs_csv(
    entity_id: Optional[int] = Query(None),
    action: Optional[str] = Query(None),
    record_type: Optional[str] = Query(None),
    user_email: Optional[str] = Query(None),
    start_date: Optional[datetime] = Query(None),
    end_date: Optional[datetime] = Query(None),
    search: Optional[str] = Query(None),
    current_user: User = Depends(require_roles(["ADMIN", "REVIEWER"])),
    db: Session = Depends(get_db)
):
    query = build_audit_query(
        db=db,
        entity_id=entity_id,
        action=action,
        record_type=record_type,
        user_email=user_email,
        start_date=start_date,
        end_date=end_date,
        search=search,
    )
    logs = query.order_by(desc(AuditLog.timestamp)).limit(2000).all()

    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow(["RicozBooks - Immutable Forensic Audit Trail"])
    writer.writerow(["Generated At (UTC)", datetime.now(timezone.utc).isoformat()])
    writer.writerow(["Generated By", current_user.email])
    writer.writerow(["Total Records", len(logs)])
    writer.writerow([])
    writer.writerow([
        "Timestamp (UTC)",
        "User Email",
        "Action",
        "Record Type",
        "Record ID",
        "IP Address",
        "Details"
    ])

    for log in logs:
        writer.writerow([
            log.timestamp.isoformat() if log.timestamp else "",
            log.user_email or "",
            log.action,
            log.record_type,
            log.record_id or "",
            log.ip_address or "",
            log.details or ""
        ])

    filename = f"audit_trail_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}.csv"
    return Response(
        content=output.getvalue(),
        media_type="text/csv",
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"'
        }
    )
